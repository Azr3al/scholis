def _normalize_s3_host(value: str) -> str:
    return value.removeprefix("https://").removeprefix("http://").rstrip("/")


def _do_public_url_bucket_prefix(cdn_host: str | None, bucket_name: str) -> str:
    """
    When one CDN hostname serves multiple Spaces buckets, public URLs need the
    bucket name in the path (path-style), e.g.
    https://schedjuice-dev.sgp1.cdn.../schedjuice-prod/media-prod/public/...
    """
    if not cdn_host:
        return ""
    if cdn_host.startswith(f"{bucket_name}."):
        return ""
    return f"{bucket_name}/"


def _resolve_do_spaces_storage(
    *,
    endpoint: str,
    legacy_custom_domain: str,
    cdn_domain: str,
    static_location: str,
    bucket_name: str,
) -> dict[str, str | None]:
    """
    Split DO Spaces origin (boto uploads/presigning) from CDN hostname (public URLs).

    S3_ENDPOINT — regional or bucket origin URL for API calls.
    S3_CDN_DOMAIN — optional CDN edge hostname for public reads.
    S3_CUSTOM_DOMAIN — legacy fallback for endpoint when S3_ENDPOINT is unset.
    """
    endpoint_raw = (endpoint or "").strip() or (legacy_custom_domain or "").strip()
    if not endpoint_raw:
        raise ImproperlyConfigured(
            "STORAGE_BACKEND=do requires S3_ENDPOINT or S3_CUSTOM_DOMAIN"
        )

    endpoint_host = _normalize_s3_host(endpoint_raw)
    if endpoint_raw.startswith("http://") or endpoint_raw.startswith("https://"):
        endpoint_url = endpoint_raw.rstrip("/")
    else:
        endpoint_url = f"https://{endpoint_host}"

    cdn_host = (
        _normalize_s3_host(cdn_domain) if (cdn_domain or "").strip() else None
    )
    if cdn_host:
        public_host = cdn_host
    elif (legacy_custom_domain or "").strip():
        public_host = _normalize_s3_host(legacy_custom_domain)
    else:
        public_host = f"{bucket_name}.sgp1.digitaloceanspaces.com"

    bucket_prefix = _do_public_url_bucket_prefix(cdn_host, bucket_name)

    if (legacy_custom_domain or "").strip():
        bucket_origin_url = f"https://{_normalize_s3_host(legacy_custom_domain)}"
    else:
        bucket_origin_url = f"https://{bucket_name}.sgp1.digitaloceanspaces.com"

    return {
        "AWS_S3_ENDPOINT_URL": endpoint_url,
        "AWS_S3_CUSTOM_DOMAIN": cdn_host,
        "AWS_S3_BUCKET_ORIGIN_URL": bucket_origin_url,
        "STATIC_URL": f"https://{public_host}/{bucket_prefix}{static_location}/",
    }


