def _load_web_push_vapid_private_key() -> str:
    raw = config("WEB_PUSH_VAPID_PRIVATE_KEY", default="", cast=str).strip().strip('"')
    default_pem = BASE_DIR / "private_key.pem"

    if not raw:
        return str(default_pem) if default_pem.is_file() else ""

    pem_path = Path(raw)
    if not pem_path.is_file() and not pem_path.is_absolute():
        pem_path = BASE_DIR / raw
    if pem_path.is_file():
        return str(pem_path.resolve())

    if "BEGIN PRIVATE KEY" in raw and "END PRIVATE KEY" in raw:
        return raw

    if default_pem.is_file():
        return str(default_pem.resolve())

    return raw


WEB_PUSH_VAPID_PRIVATE_KEY = _load_web_push_vapid_private_key()

