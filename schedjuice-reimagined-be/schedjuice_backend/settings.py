# Use 127.0.0.1 in REDIS_URL on Windows + WSL: "localhost" may resolve to ::1 while
# Redis listens on IPv4 only, breaking channels_redis during WebSocket connect.


def _redis_url_with_db(db: int) -> str:
    """One Redis instance, but a distinct logical DB per role (channels /0,
    cache /1, celery broker /2, celery results /3, django-q2 /4) so cache
    operations can never touch broker data and per-role memory stays
    observable via INFO keyspace."""
    from urllib.parse import urlsplit, urlunsplit

    base = config("REDIS_URL", default="redis://127.0.0.1:6379")
    return urlunsplit(urlsplit(base)._replace(path=f"/{db}"))


